@pytest.mark.parametrize("format_id", [1055, 1061])
@pytest.mark.parametrize("damage", ["missing", "truncated"])
@pytest.mark.parametrize("replace_all", [False, True])
def test_regenerate_missing_artwork_only_when_every_owner_has_new_pixels(
    format_id: int, damage: str, replace_all: bool
) -> None:
    cover = (
        COVER
        if format_id == 1055
        else replace(COVER, format_id=1061, width=56, height=56, row_bytes=112)
    )
    target = replace(TARGET, cover_formats=(cover,))
    source, file = with_shared_artwork(target=target)
    original = source.serialize()
    resources = WriteResources(artwork=(BLUE,), file_inventory=())
    if damage == "truncated":
        resources = resources_for(file)
        dependency = replace(
            resources.files[0].dependency, size=1, sha256=content_sha256(b"x")
        )
        resources = replace(
            resources,
            files=(replace(resources.files[0], dependency=dependency, data=b"x"),),
            file_inventory=(dependency,),
        )
    first, second = source.snapshot.tracks
    desired = replace(
        source.snapshot,
        tracks=(
            replace(first, artwork_id=BLUE.artwork_id),
            replace(second, artwork_id=BLUE.artwork_id) if replace_all else second,
        ),
    )
    result = source.prepare(
        source.analyze(source.begin_draft(desired), target), resources
    )
    if not replace_all:
        assert result.prepared is None
        return
    assert result.prepared is not None, result.issues
    prepared = result.prepared
    assert prepared.artwork is not None and original.artwork is not None
    assert len(prepared.artwork_files) == 1
    generated = prepared.artwork_files[0]
    assert generated.relative_path == file.relative_path.replace("_1.ithmb", "_2.ithmb")
    assert len(generated.data) == cover.height * cover.row_bytes
    old_row = parse_ArtworkDB(original.artwork).find_chunks(MhiiHeader)[0].chunk
    retained_row = parse_ArtworkDB(prepared.artwork).find_chunks(MhiiHeader)[0].chunk
    assert retained_row.children == old_row.children
    assert retained_row.header == replace(old_row.header, db_track_id_ref=0)
    output = IPodLibrary(prepared.itunes).with_artwork(prepared.artwork)
    for track in output.snapshot.tracks:
        assert track.artwork_id != first.artwork_id
        read = output.artwork_read(track.artwork_id, (cover,), 56)
        assert read is not None
        decoded = read.decode(read_content(generated.data, read.offset, read.length))
        assert decoded.rgb888[2] > 240
    assert source.serialize() == original
    # Retained damaged history must not block another ordinary cover edit after
    # its live owners were successfully regenerated by the previous Sync.
    subsequent = replace(
        output.snapshot,
        tracks=(
            replace(output.snapshot.tracks[0], artwork_id=BLUE.artwork_id),
            output.snapshot.tracks[1],
        ),
    )
    next_result = output.prepare(
        output.analyze(output.begin_draft(subsequent), target), resources_for(generated)
    )
    assert next_result.prepared is not None, next_result.issues
    assert next_result.prepared.snapshot.tracks[1] == output.snapshot.tracks[1]


@pytest.mark.parametrize(
    "cover",
    [
        CoverFormat(1060, 4, 6, 12, CoverPixelFormat.RGB565_BE_90),
        CoverFormat(1055, 4, 6, 0, CoverPixelFormat.RGB565_LE),
        CoverFormat(1019, 4, 6, 0, CoverPixelFormat.I420_LE),
    ],
)
def test_regeneration_keeps_healthy_surviving_rasters_and_skips_damaged_shard(
    cover: CoverFormat,
) -> None:
    target = replace(TARGET, cover_formats=(cover,))
    source = library()
    first, second = source.snapshot.tracks
    initial = source.prepare(
        source.analyze(
            source.begin_draft(
                replace(
                    source.snapshot,
                    tracks=(
                        replace(first, artwork_id=RED.artwork_id),
                        replace(second, artwork_id=BLUE.artwork_id),
                    ),
                )
            ),
            target,
        ),
        WriteResources(artwork=(RED, BLUE), file_inventory=()),
    )
    assert initial.prepared is not None and initial.prepared.artwork is not None
    source = IPodLibrary(initial.prepared.itunes).with_artwork(initial.prepared.artwork)
    file = initial.prepared.artwork_files[0]
    prefix = read_content(file.data, 0, len(file.data) // 2)
    resources = resources_for(file)
    dependency = replace(
        resources.files[0].dependency, size=len(prefix), sha256=content_sha256(prefix)
    )
    replacement = ArtworkAsset(-3, ArtworkPixels(2, 2, bytes((0, 255, 0)) * 4))
    resources = replace(
        resources,
        artwork=(replacement,),
        files=(replace(resources.files[0], dependency=dependency, data=prefix),),
        file_inventory=(dependency,),
    )
    first, second = source.snapshot.tracks
    desired = replace(
        source.snapshot,
        tracks=(first, replace(second, artwork_id=replacement.artwork_id)),
    )
    result = source.prepare(
        source.analyze(source.begin_draft(desired), target), resources
    )
    assert result.prepared is not None, result.issues
    prepared = result.prepared
    assert prepared.snapshot.tracks[0] == first
    assert prepared.artwork_files[0].relative_path != file.relative_path
    assert len(prepared.artwork_files[0].data) == len(prefix)


def test_unprojectable_retained_filename_is_reserved_for_new_shard() -> None:
    source, file = with_shared_artwork()
    original = source.serialize()
    assert original.artwork is not None
    document = parse_ArtworkDB(original.artwork)
    row = document.find_chunks(MhiiHeader)[0].chunk
    container = row.children[0]
    assert isinstance(container.payload, MhodContainerPayload)
    location = container.payload.child
    name = location.children[0]
    assert isinstance(name.payload, MhodStringPayload)
    empty = replace(
        row,
        header=replace(row.header, image_id=77, db_track_id_ref=0),
        children=(
            replace(
                container,
                payload=replace(
                    container.payload,
                    child=replace(
                        location,
                        header=replace(location.header, image_size=0, image_size_2=0),
                        children=(
                            replace(
                                name,
                                payload=replace(name.payload, value=":F1055_2.ithmb"),
                            ),
                        ),
                    ),
                ),
            ),
            *row.children[1:],
        ),
    )
    dataset = next(
        s for s in document.find_chunks(MhsdHeader) if s.chunk.header.dataset_type == 1
    )
    document = document.replace_chunk(
        dataset,
        replace(
            dataset.chunk, children=(dataset.chunk.children[0].append_child(empty),)
        ),
    )
    source = IPodLibrary(original.itunes).with_artwork(write_ArtworkDB(document))
    first, second = source.snapshot.tracks
    desired = replace(
        source.snapshot, tracks=(replace(first, artwork_id=BLUE.artwork_id), second)
    )
    result = source.prepare(
        source.analyze(
            source.begin_draft(desired),
            replace(TARGET, max_artwork_file_bytes=len(file.data)),
        ),
        resources_for(file),
    )
    assert result.prepared is not None, result.issues
    assert result.prepared.artwork_files[0].relative_path.endswith("F1055_3.ithmb")
