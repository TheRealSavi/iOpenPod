"""Captured Calendar and Alarm views and explicit, connection-bound edits."""

from dataclasses import dataclass, field
from enum import StrEnum

from whenever import Date, PlainDateTime, Time

from device_registry import ExtrasSupport
from iPodDB.alarms import ClockCity, CountdownTimerChanges, CountdownTimerSnapshot
from iPodDB.calendar import (
    CalendarComponent,
    CalendarEntry,
    CalendarEntryChanges,
    CalendarEntryDraft,
    CalendarOccurrence,
    calendar_zone_names,
)
from iPodDB.library import AlarmPlaylistCatalog
from storage import FileFingerprint, FilePrecondition


@dataclass(frozen=True, slots=True)
class CalendarItem:
    document_key: str
    entry: CalendarEntry
    calendar_name: str | None = None
    occurrence: CalendarOccurrence | None = None
    source_calendar: CalendarComponent | None = field(default=None, repr=False)

    @property
    def index(self) -> int:
        return self.entry.entry_id

    @property
    def zone_names(self) -> tuple[str, ...]:
        if self.source_calendar is None:
            return ()
        return calendar_zone_names(
            self.source_calendar, before_offset=self.entry.component.start_offset
        )


@dataclass(frozen=True, slots=True)
class AlarmSound:
    """One source-qualified native sound choice, never a Host media path."""

    class Kind(StrEnum):
        BEEP = "beep"
        PLAYLIST = "playlist"
        TONE = "tone"

    kind: Kind
    name: str
    playlist_id: int | None = None
    playlist_index: int | None = None

    tone_name: str | None = None


@dataclass(frozen=True, slots=True)
class AlarmItem:
    index: int
    display_label: str
    time: PlainDateTime | Time | None
    repeat: int | None
    editable: bool
    detail: str = ""
    repeat_editable: bool = False
    enabled: bool | None = None
    enabled_editable: bool = False
    label_index: int | None = None
    label_editable: bool = False
    sound: AlarmSound | None = None
    sound_editable: bool = False
    sound_description: str = ""
    playlist_index: int | None = None
    clock_city: ClockCity | None = None
    daylight_saving: bool | None = None
    daylight_saving_editable: bool = False


@dataclass(frozen=True, slots=True)
class ExtrasFile:
    """Original bytes and precondition captured through Storage, never a Host path."""

    key: str
    data: bytes
    fingerprint: FileFingerprint


@dataclass(frozen=True, slots=True)
class CalendarGroup:
    """Exact-name grouping with retained file identities, including empty calendars."""

    name: str | None
    document_keys: tuple[str, ...]
    editable: bool
    zones: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class ExtrasCatalog:
    calendar: tuple[CalendarItem, ...] = ()
    alarms: tuple[AlarmItem, ...] = ()
    issues: tuple[str, ...] = ()
    support: ExtrasSupport | None = None
    files: tuple[ExtrasFile, ...] = ()
    calendars: tuple[CalendarGroup, ...] = ()
    timer: CountdownTimerSnapshot | None = None
    can_create_alarm: bool = False
    alarm_sounds: tuple[AlarmSound, ...] = ()
    alarm_playlists: AlarmPlaylistCatalog | None = None
    playlist_source: FilePrecondition | None = None
    tone_dependencies: tuple[FilePrecondition, ...] = ()
    tone_inventory: tuple[str, ...] | None = None
    clock_cities: tuple[ClockCity, ...] = ()
    playlist_dependencies: tuple[FilePrecondition, ...] = ()


@dataclass(frozen=True, slots=True)
class SaveCalendar:
    edit: CalendarEntryDraft | CalendarEntryChanges
    existing: CalendarItem | None = None
    destination: CalendarGroup | None = None


@dataclass(frozen=True, slots=True)
class RemoveCalendar:
    item: CalendarItem


@dataclass(frozen=True, slots=True)
class SkipCalendarOccurrence:
    item: CalendarItem
    day: Date
    start_day: Date


@dataclass(frozen=True, slots=True)
class ImportCalendar:
    """Host selection read in the worker; destination is generated by the service."""

    host_path: str
    name: str | None = None


@dataclass(frozen=True, slots=True)
class CreateCalendar:
    name: str


@dataclass(frozen=True, slots=True)
class RenameCalendar:
    calendar: CalendarGroup
    name: str


@dataclass(frozen=True, slots=True)
class SaveAlarm:
    item: AlarmItem
    time: PlainDateTime | Time
    repeat: int | None = None
    enabled: bool | None = None
    label_index: int | None = None
    sound: AlarmSound | None = None
    daylight_saving: bool | None = None


@dataclass(frozen=True, slots=True)
class CreateAlarm:
    time: PlainDateTime
    repeat: int = 0
    enabled: bool = True
    label_index: int = 3
    sound: AlarmSound | None = None


@dataclass(frozen=True, slots=True)
class RemoveAlarm:
    item: AlarmItem


@dataclass(frozen=True, slots=True)
class CreateClockAlarm:
    city: ClockCity
    time: Time
    daylight_saving: bool = False
    enabled: bool = False
    sound: AlarmSound | None = None


@dataclass(frozen=True, slots=True)
class SaveTimerSettings:
    changes: CountdownTimerChanges


type ExtrasChange = (
    SaveCalendar
    | RemoveCalendar
    | SkipCalendarOccurrence
    | ImportCalendar
    | SaveAlarm
    | CreateCalendar
    | RenameCalendar
    | CreateAlarm
    | RemoveAlarm
    | SaveTimerSettings
    | CreateClockAlarm
)
