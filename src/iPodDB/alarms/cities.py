def clock_city(region: int | None, ordinal: int | None) -> ClockCity | None:
    """Resolve the saved region and city pair without inventing unknown names."""
    return next(
        (
            city
            for city in CLOCK_CITIES
            if (city.region, city.ordinal) == (region, ordinal)
        ),
        None,
    )
