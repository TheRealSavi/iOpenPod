"""Curated binary observation metadata from the 2026-11-07 firmware research.

Only named fields and bounded resource catalogs are included. These are read
descriptions, never writer allowlists. Original-image hashes qualify the research;
profile identity, file extent and version qualify a captured Preferences file.
No firmware, emulator, lab path or lab dependency is required at runtime.

Evidence hashes below identify the reviewed inventory/supplement, in the same
order as its accompanying report name under docs/research/. Metadata deliberately
keeps unresolved semantics explicit instead of inheriting neighboring models.
"""

from dataclasses import dataclass
from typing import Literal

from iPodDB.preferences.definitions import PREFERENCES_ALARM_OFFSET, PreferencesProfile

type FieldKind = Literal[
    "integer",
    "version",
    "reset",
    "shuffle",
    "clicker",
    "mask",
    "clock_format",
    "utf16",
    "mini_zone",
    "percentage",
    "city",
    "balance",
    "boolean",
    "early_transition",
    "later_transition",
]


@dataclass(frozen=True, slots=True)
class BinaryObservationField:
    """A non-authorizing saved-field description; choices name known raw values."""

    offset: int
    size: int
    key: str
    label: str
    category: str
    detail: str
    choices: tuple[tuple[int, str], ...] = ()
    kind: FieldKind = "integer"
    signed: bool = False
    partial: bool = True


@dataclass(frozen=True, slots=True)
class BinaryProfileEvidence:
    """Exact input qualification and the observations independently bound to it."""

    firmware_sha256: tuple[str, ...]
    fields: tuple[BinaryObservationField, ...]


