def _units(value: str) -> tuple[int, ...]:
    data = value.encode("utf-16-le", errors="surrogatepass")
    return struct.unpack("<" + "H" * (len(data) // 2), data)


def compare_alarm_names(left: str, right: str) -> int:
    """Compare counted names; the caller supplies the native displayed prefix."""
    a, b = _units(left), _units(right)
    ai = bi = 0
    while ai < len(a) and a[ai] <= 0x20:
        ai += 1
    while bi < len(b) and b[bi] <= 0x20:
        bi += 1
    a, b = a[ai:], b[bi:]
    for x, y in zip(a, b, strict=False):
        if not _fast(x) or not _fast(y):
            break
        x = x - 0x20 if 0x61 <= x <= 0x7A else x
        y = y - 0x20 if 0x61 <= y <= 0x7A else y
        if x != y:
            return (x > y) - (x < y)
    else:
        return (len(a) > len(b)) - (len(a) < len(b))
    aw = tuple(
        weight for unit in a if (weight := _WEIGHTS[unit] >> 16 if unit < 256 else unit)
    )
    bw = tuple(
        weight for unit in b if (weight := _WEIGHTS[unit] >> 16 if unit < 256 else unit)
    )
    return (aw > bw) - (aw < bw)


def _fast(unit: int) -> bool:
    # Digits force the primary-weight path even though the ASCII table admits them.
    return unit in (0x20, 0x21, 0x2E) or 0x41 <= unit <= 0x5A or 0x61 <= unit <= 0x7A
